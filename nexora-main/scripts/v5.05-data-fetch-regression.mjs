import fs from "node:fs";
const read = (f) => fs.readFileSync(f, "utf8");
const dashboard = read("src/components/dashboard.tsx");
const bell = read("src/components/notifications/notification-bell.tsx");
const observer = read("src/components/nexo/nexo-live-observer.tsx");
const refresh = read("src/lib/notifications/client-refresh.ts");
const api = read("src/app/api/notifications/refresh/route.ts");
if (!dashboard.includes("const scheduleLoad")) throw new Error("Dashboard realtime reload is not debounced");
if (!bell.includes("refreshNotifications({ force: true })")) throw new Error("Initial notification refresh is not explicit");
if (bell.includes('await fetch("/api/notifications/refresh"')) throw new Error("NotificationBell still refreshes on every load");
if (!observer.includes("void refreshNotifications()")) throw new Error("Live observer does not use throttled refresh");
if (!refresh.includes("15_000")) throw new Error("Notification refresh throttle missing");
if (api.includes("error: error.message")) throw new Error("Raw notification RPC error is exposed");
console.log("✓ v5.05 data-fetch regression");
