import fs from 'node:fs';
const checks = [];
const read = (p) => fs.readFileSync(p,'utf8');
const lib = read('src/lib/lia/feedback-learning.ts');
const route = read('src/app/api/lia/feedback/route.ts');
const mig = read('supabase/migrations/0104_lia_feedback_learning_governance.sql');
checks.push(['feedback signals allow-list', ['helpful','not_helpful','accepted','rejected','corrected'].every(x=>lib.includes('"'+x+'"'))]);
checks.push(['candidate gate immutable', lib.includes('learningGate: "candidate"') && mig.includes("check (learning_gate = 'candidate')")]);
checks.push(['no model weight updates', lib.includes('modelWeightUpdate: false') && mig.includes('model_weight_update boolean not null default false')]);
checks.push(['no policy updates', lib.includes('policyUpdate: false') && mig.includes('policy_update boolean not null default false')]);
checks.push(['no financial fact updates', lib.includes('financialFactUpdate: false') && mig.includes('financial_fact_update boolean not null default false')]);
checks.push(['csrf protected', route.includes('assertSameOrigin(request)')]);
checks.push(['authenticated user binding', route.includes('auth.getUser()') && route.includes('user_id: user.id')]);
checks.push(['note bounded', lib.includes('slice(0, 1000)')]);
checks.push(['rls enabled', mig.includes('enable row level security')]);
checks.push(['owner select/insert only', mig.includes('for select to authenticated using (auth.uid() = user_id)') && mig.includes('for insert to authenticated with check (auth.uid() = user_id)')]);
for (const [name,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${name}`);
if (checks.some(([,ok])=>!ok)) process.exit(1);
console.log(`V5.08.50 regression: ${checks.length}/${checks.length} PASS`);
